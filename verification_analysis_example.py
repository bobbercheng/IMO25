def is_valid_k_configuration(n: int, k: int, lines: List[Set[int]],
                             marking: Set[int]) -> bool:
    """
    Formal specification: A configuration is k-intersecting if:
    1. We have n lines
    2. We mark exactly k points
    3. Every line contains at least one marked point
    """
    if len(marking) != k:
        return False

    for line in lines:
        if not any(point in line for point in marking):
            return False

    return True


